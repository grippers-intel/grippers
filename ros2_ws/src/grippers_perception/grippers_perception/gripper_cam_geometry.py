"""그리퍼캠 프레임의 방향을 한 곳에서 정한다.

## 왜 필요한가

**그리퍼캠(ABKO APC-850 광각)은 거꾸로 장착돼 있다** (2026-08-30 교체·재장착).
화각을 맞추다 보니 그 방향이 됐다. 그래서 센서가 내보내는 raw 프레임은
상하가 뒤집혀 있고, 쓰기 전에 180도 돌려야 사람이 보는 방향과 같아진다.

이 파일이 존재하는 이유는 **회전을 빠뜨리면 아무 에러 없이 조용히 틀리기**
때문이다. 다음 두 곳이 같은 장치를 각각 연다.

    gripper_cam_publisher_node   /dev/gripper_cam -> gripper_cam/image_raw
    perception_node              /dev/gripper_cam -> confirm_grasp diff

한쪽만 고치면 두 경로가 서로 다른 세상을 본다.

## VLA 정책과의 계약

시연 데이터는 노트북에서 LeRobot 의 카메라 설정으로 찍는다.

    'gripper': {..., 'rotation': 180}

즉 **학습 데이터는 이미 180도 돌아간 상태로 저장돼 있다.** Pi 에서 정책을
돌릴 때 같은 회전을 안 걸면 정책은 상하 반전된 입력을 받는다. 학습이 안 되는
게 아니라 **엉뚱하게 동작한다** — 그리고 원인을 찾기가 매우 어렵다.

    학습 때 정책이 본 화면  ==  추론 때 정책이 보는 화면

이 등식이 전부다. 회전을 하느냐 마느냐가 아니라 양쪽이 같으냐가 요점이다.

## ROI 상수도 여기에 매여 있다

`perception_node.GRIPPER_CAM_ROI = (0.30, 0.55, 0.70, 1.00)` 은 **손가락이
프레임 하단 중앙에 잡힌다**는 전제 위에 있다(2026-08-21 실기 스냅샷). 회전을
읽는 즉시 걸어 주면 그 전제가 그대로 유지된다. 회전을 빼면 손가락이 상단으로
가므로 ROI 를 `(0.30, 0.00, 0.70, 0.45)` 로 바꿔야 한다.

**읽자마자 돌리는 쪽을 택했다** — 하류 코드가 장착 방향을 몰라도 되게.

⚠️ 카메라를 다시 달면 이 값을 재확인할 것. 스냅샷 한 장이면 판정된다 —
손가락(어두운 쐐기 둘)이 프레임 아래쪽에 있으면 맞다.
"""

import cv2

#: 장착이 뒤집혀 있으므로 읽은 프레임을 180도 돌린다.
#: 카메라를 바로 달게 되면 None 으로 바꾸면 된다(하류 코드는 그대로 둔다).
GRIPPER_CAM_ROTATION = cv2.ROTATE_180


def orient(frame):
    """raw 프레임을 '사람이 보는 방향'으로 돌린다.

    `GRIPPER_CAM_ROTATION` 이 None 이면 그대로 돌려준다. 프레임이 None 이면
    그대로 None — 호출자의 실패 처리를 가로채지 않는다.
    """
    if frame is None or GRIPPER_CAM_ROTATION is None:
        return frame
    return cv2.rotate(frame, GRIPPER_CAM_ROTATION)
